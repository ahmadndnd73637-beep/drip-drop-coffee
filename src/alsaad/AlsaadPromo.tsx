import { iris } from "@remotion/transitions/iris";
import { slide } from "@remotion/transitions/slide";
import { wipe } from "@remotion/transitions/wipe";
import { linearTiming, springTiming, TransitionSeries } from "@remotion/transitions";
import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile, useVideoConfig } from "remotion";
import { AlsaadReveal } from "./AlsaadReveal";
import {
  CheckScene,
  HelpScene,
  HeroScene,
  OutroScene,
  PriceScene,
  type SceneCopy,
  Sfx,
  SpecsScene,
  UseScene,
} from "./scenes";

export type AlsaadPromoProps = {
  words: string[];
  copy: SceneCopy;
};

// The logo reveal runs until its dot has rolled out of frame.
const INTRO = 262;
const SCENE = 115;
const OUTRO = 230;
const T = 15;
export const ALSAAD_PROMO_DURATION = INTRO + SCENE * 6 + OUTRO - T * 6;

export const AlsaadPromo: React.FC<AlsaadPromoProps> = ({ words, copy }) => {
  const { fps, width, height } = useVideoConfig();
  const irisIn = iris({ width, height });
  const timing = linearTiming({ durationInFrames: T });
  const springy = springTiming({ config: { damping: 200 }, durationInFrames: T });

  return (
    <AbsoluteFill style={{ background: "#fff" }}>
      {/* Original music bed, generated by scripts/make-alsaad-music.py on this timeline */}
      <Audio name="Music" src={staticFile("music/alsaad-beat.ogg")} volume={0.55} premountFor={fps} />
      <Sequence name="Logo reveal" durationInFrames={INTRO} premountFor={fps}>
        <AlsaadReveal words={words} />
      </Sequence>
      <Sequence name="Scenes" from={INTRO} premountFor={fps}>
        <TransitionSeries>
          <TransitionSeries.Sequence name="Hero" durationInFrames={SCENE} premountFor={fps}>
            <HeroScene copy={copy} />
          </TransitionSeries.Sequence>
          <TransitionSeries.Transition presentation={irisIn} timing={timing} />
          <TransitionSeries.Sequence name="Use cases" durationInFrames={SCENE} premountFor={fps}>
            <UseScene copy={copy} />
          </TransitionSeries.Sequence>
          <TransitionSeries.Transition
            presentation={slide({ direction: "from-bottom" })}
            timing={springy}
          />
          <TransitionSeries.Sequence name="Specs" durationInFrames={SCENE} premountFor={fps}>
            <SpecsScene copy={copy} />
          </TransitionSeries.Sequence>
          <TransitionSeries.Transition presentation={irisIn} timing={timing} />
          <TransitionSeries.Sequence name="Checked" durationInFrames={SCENE} premountFor={fps}>
            <CheckScene copy={copy} />
          </TransitionSeries.Sequence>
          <TransitionSeries.Transition
            presentation={wipe({ direction: "from-right" })}
            timing={springy}
          />
          <TransitionSeries.Sequence name="Price" durationInFrames={SCENE} premountFor={fps}>
            <PriceScene copy={copy} />
          </TransitionSeries.Sequence>
          <TransitionSeries.Transition presentation={irisIn} timing={timing} />
          <TransitionSeries.Sequence name="Help" durationInFrames={SCENE} premountFor={fps}>
            <HelpScene copy={copy} />
          </TransitionSeries.Sequence>
          <TransitionSeries.Transition
            presentation={slide({ direction: "from-bottom" })}
            timing={springy}
          />
          <TransitionSeries.Sequence name="Outro" durationInFrames={OUTRO} premountFor={fps}>
            <OutroScene copy={copy} />
          </TransitionSeries.Sequence>
        </TransitionSeries>
        {/* A soft swoosh on every cut between scenes */}
        {[1, 2, 3, 4, 5, 6].map((i) => (
          <Sfx key={i} file="transition.ogg" at={i * (SCENE - T)} volume={0.4} />
        ))}
      </Sequence>
    </AbsoluteFill>
  );
};
